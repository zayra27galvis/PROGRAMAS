print("CONTROL DE VUELOS")
print(" ")
codVuelo = int(input("Codigo del vuelo: "))
aerolinea = input("Nombre de la aerolinea: ")
origen = input("Ciudad de origen: ")
destino = input("Ciudad de destino: ")
modeloAvion = input("Modelo del avion: ")
distancia = float(input("Distancia del vuelo en km: "))
velocidad = float(input("Velocidad promedio del avion en km/h: "))
consumoHora = float(input("Consumo de combustible por hora en litros: "))
tiempo = distancia / velocidad
combustible = tiempo * consumoHora
print(" ")
print("INFORMACION DEL VUELO")
print("Codigo:", codVuelo)
print("Aerolinea:", aerolinea)
print("Origen:", origen)
print("Destino:", destino)
print("Modelo del avion:", modeloAvion)
print("Distancia:", distancia, "km")
print("Velocidad promedio:", velocidad, "km/h")
print("Tiempo estimado:", tiempo, "horas")
print("Combustible necesario:", combustible, "litros")